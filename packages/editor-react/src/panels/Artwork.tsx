export interface ArtworkProps {
  db: Db;
  adapter: ArtworkAdapter;
  /**
   * Artwork the page now knows about that its bundled source does not. The
   * host layers this over whatever it built at compile time, which is what
   * makes a just-uploaded picture show up in the schematic without a reload.
   */
  onOverlayChange?: (overlay: ArtworkOverlay) => void;
  /** the definition to open first — usually one the open design uses */
  initialDefId?: string;
}

/** Every definition a depiction can be attached to, in one searchable list. */
export function depictableDefinitions(
  db: Db,
): { id: string; label: string; kind: 'connector' | 'component' | 'pcba' }[] {
  return [
    ...db.connectors.map((c) => ({ id: c.id, label: c.label, kind: 'connector' as const })),
    ...db.pcbas.map((p) => ({ id: p.id, label: p.label, kind: 'pcba' as const })),
    ...db.components.map((c) => ({ id: c.id, label: c.label, kind: 'component' as const })),
  ];
}

export function ArtworkPane(props: ArtworkProps): JSX.Element {
  const entries = useMemo(() => depictableDefinitions(props.db), [props.db]);
  const [query, setQuery] = useState('');
  const [defId, setDefId] = useState<string | undefined>(
    () => props.initialDefId ?? entries[0]?.id,
  );
  const overlay = useRef<ArtworkOverlay>(EMPTY_OVERLAY);

  const { onOverlayChange } = props;
  const onOverlay = useCallback(
    (id: string, detail: ArtworkDetail, assets: Record<string, DepictionArtwork>): void => {
      if (detail.meta === undefined && Object.keys(assets).length === 0) return;
      overlay.current = overlayWith(overlay.current, id, detail.meta, assets);
      onOverlayChange?.(overlay.current);
    },
    [onOverlayChange],
  );

  const shown = useMemo(() => {
    const needle = query.trim().toLowerCase();
    if (needle === '') return entries;
    return entries.filter(
      (entry) =>
        entry.id.toLowerCase().includes(needle) || entry.label.toLowerCase().includes(needle),
    );
  }, [entries, query]);

  return (
    <div className="cs-artwork">
      <aside className="cs-artwork-picker">
        <input
          className="cs-input"
          value={query}
          placeholder="find a part"
          aria-label="find a part"
          onChange={(event) => setQuery(event.target.value)}
        />
        <ul className="cs-scroll">
          {shown.map((entry) => (
            <li key={`${entry.kind}-${entry.id}`}>
              <button
                type="button"
                className={classes('cs-artwork-pick', defId === entry.id && 'is-active')}
                aria-pressed={defId === entry.id}
                onClick={() => setDefId(entry.id)}
              >
                <span className="cs-part-label">{entry.label}</span>
                <span className="cs-part-detail">
                  {entry.kind} · {entry.id}
                </span>
              </button>
            </li>
          ))}
          {shown.length === 0 ? <li className="cs-empty">nothing matches “{query}”</li> : null}
        </ul>
      </aside>
      {defId === undefined ? (
        <p className="cs-empty">This catalog has no parts to draw yet.</p>
      ) : (
        <ArtworkDetailPane key={defId} defId={defId} adapter={props.adapter} onOverlay={onOverlay} />
      )}
    </div>
  );
}
