function Problem(props: {
  message: string;
  hint?: string;
  issues?: Issue[];
  guidance?: string[];
  onDismiss?: () => void;
}): JSX.Element {
  return (
    <div className="cs-problem" role="alert">
      <strong>{props.message}</strong>
      {props.hint === undefined ? null : <span className="cs-problem-hint">{props.hint}</span>}
      {props.guidance === undefined || props.guidance.length === 0 ? null : (
        // shown exactly as the importer wrote it: the ladder's advice is the
        // product of a refusal, and paraphrasing it would lose the command
        <pre className="cs-artwork-guidance">{props.guidance.join('\n')}</pre>
      )}
      {props.issues === undefined || props.issues.length === 0 ? null : (
        <ul className="cs-problem-list">
          {props.issues.map((issue, index) => (
            <li key={`${issue.code}-${index}`}>{issue.message}</li>
          ))}
        </ul>
      )}
      {props.onDismiss === undefined ? null : (
        <button type="button" onClick={props.onDismiss}>
          dismiss
        </button>
      )}
    </div>
  );
}

/** The `<img>` src for one asset, self-contained either way. */
export function artworkSrc(art: DepictionArtwork | undefined): string | undefined {
  if (art === undefined) return undefined;
  if (art.kind === 'raster') return art.dataUri;
  if (art.source === undefined) return undefined;
  // an <img> cannot run script, so an SVG data URI is the safe way to show
  // artwork the editor did not author
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(art.source)}`;
}

/** A frame out of anything that carries `widthUnits`/`heightUnits` — an
 * `ArtworkView` (the detail's own shape) or a `DepictionMeta` asset entry
 * (the gerber display reads straight off `meta.views`). */
function frameOf(view: { widthUnits?: number; heightUnits?: number } | undefined): Frame | undefined {
  if (view?.widthUnits === undefined || view.heightUnits === undefined) return undefined;
  return { widthUnits: view.widthUnits, heightUnits: view.heightUnits };
}

