/**
 * The Artwork view: drop a picture of a part in, then click its pins onto it.
 *
 * This is the GUI half of `specs/depictions.md` — the half that means nobody
 * has to hand-edit a `meta.json` or run a CLI to get real board pictures into
 * the schematic. Four things it is built around:
 *
 * 1. **Upload is a conversation, not a dialog box.** The host runs the import
 *    ladder's normalisation and hands back either what it changed ("emptied 12
 *    area fills — the house style is line art") or a refusal that names the
 *    rung the file is on and the one command that gets it onto a rung the tool
 *    supports. Both are shown verbatim: that paragraph *is* the feature.
 * 2. **Anchoring is click-a-pin, click-the-picture.** The terminal list is a
 *    checklist that arms the next unanchored pin for you, so a 21-pin connector
 *    is 21 clicks. An anchor that is slightly off is dragged, not retyped.
 * 3. **The mirror is shown, not explained.** The solder side sits beside the
 *    face view, updating live from the anchors being placed, labelled as
 *    generated. The rule the spec cares most about is the one the user watches
 *    happen.
 * 4. **What you just saved is what the schematic draws.** After a successful
 *    write the pane pulls the fresh manifest and bytes back and hands them
 *    upward as an overlay, so the preview redraws without a reload.
 *
 * No URL, no `fetch` and no file path appears here: the host supplies an
 * `ArtworkAdapter`, exactly as it supplies a `PersistenceAdapter`.
 */

