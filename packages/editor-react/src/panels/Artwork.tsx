export interface DetailProps {
  defId: string;
  adapter: ArtworkAdapter;
  /**
   * The connector's own definition, when this is a connector: its built-in
   * drawing (`connector-art.ts`) is shown first, as what the builder uses,
   * and uploaded artwork becomes an optional extra (50a.38).
   */
  connector?: ConnectorDefinition;
  /** the body that connector is built on: the built-in drawing is the body's */
  body?: ConnectorBody;
  /** labels of every pinout on that body — they all share this drawing */
  sharedBy?: readonly string[];
  /** the shared asset library, for "pick existing" beside each upload */
  assets?: AssetsAdapter;
  onOverlay: (
    defId: string,
    detail: ArtworkDetail,
    assets: Record<string, DepictionArtwork>,
  ) => void;
}

export function ArtworkDetailPane(props: DetailProps): JSX.Element {
  const { defId, adapter, onOverlay } = props;
  const [detail, setDetail] = useState<ArtworkDetail | undefined>(undefined);
  const [art, setArt] = useState<Record<string, DepictionArtwork>>({});
  const [state, setState] = useState<AnchoringState>(() => beginAnchoring({}));
  const [saving, setSaving] = useState(false);
  const [notice, setNotice] = useState<string | undefined>(undefined);
  const [problem, setProblem] = useState<
    { message: string; hint?: string; issues?: Issue[] } | undefined
  >(undefined);
  const [loadProblem, setLoadProblem] = useState<string | undefined>(undefined);

  /**
   * Re-read everything and hand it upward as an overlay.
   *
   * The bytes are fetched here rather than left to the host because *this* is
   * the moment the page learns about artwork its bundle never had: the studio's
   * `DepictionSource` was globbed at build time, and a file uploaded thirty
   * seconds ago is not in it. Pulling the manifest and the assets back after
   * every successful write is what lets the schematic redraw without a reload.
   */
  const refresh = useCallback(async (): Promise<void> => {
    const result = await adapter.detail(defId);
    if (!result.ok) {
      setLoadProblem(`${result.message} ${result.hint ?? ''}`.trim());
      setDetail(undefined);
      return;
    }
    setLoadProblem(undefined);
    setDetail(result.value);
    setState(beginAnchoring(result.value.pinAnchors));
    const assets: Record<string, DepictionArtwork> = {};
    for (const view of result.value.views) {
      const bytes = await adapter.artwork(defId, view.view);
      if (bytes.ok) assets[view.view] = bytes.value;
    }
    setArt(assets);
    onOverlay(defId, result.value, assets);
  }, [adapter, defId, onOverlay]);

  useEffect(() => {
    void refresh();
  }, [refresh]);

  const definition = detail?.definition;
  const terminals: ArtworkTerminal[] = definition?.terminals ?? [];
  const progress = useMemo(() => anchorProgress(terminals, state.anchors), [terminals, state.anchors]);
  const missingSentence = unanchoredSentence(progress, definition?.label ?? defId, detail?.usedBy);
  /**
   * Gerber-sourced boards (`sourceKind: 'gerber'`) are the production
   * fabrication output, not a picture someone drew — regenerated by
   * `scripts/import-gerbers.ts`, never hand-uploaded or hand-anchored
   * (3pn.4). `isGerberBoard` is the same check the canvas uses to decide
   * whether to draw real board art.
   */
  const gerber = isGerberBoard(detail?.meta);

  const frameView = useMemo(() => {
    if (detail === undefined) return undefined;
    const named = detail.views.find((view) => view.view === detail.anchorFrame);
    return named ?? detail.views.find((view) => !view.derived);
  }, [detail]);
  const frame = frameOf(frameView);

  const mirrorName = frameView === undefined ? undefined : mirrorCounterpart(frameView.view);
  const mirrorAxis =
    (mirrorName === undefined
      ? undefined
      : detail?.views.find((view) => view.view === mirrorName)?.mirrorAxis) ?? 'x';
  const mirrored = useMemo(
    () => (frame === undefined ? {} : derivedAnchors(state.anchors, mirrorAxis, frame)),
    [state.anchors, mirrorAxis, frame],
  );

  const dirty = detail === undefined ? false : anchorsDiffer(state.anchors, detail.pinAnchors);

  /** the builder's own drawing of this connector, when its family has one */
  const builtIn = useMemo(() => builtInConnectorArt(props.connector, props.body), [props.connector, props.body]);
  /** anything uploaded that pins are placed on by hand */
  const manual = frameView !== undefined;
  const anchorChip = ((): { text: string; title: string; done: boolean } => {
    const total = terminals.length;
    if (gerber) {
      const placed = Math.max(0, total - (detail?.unanchored.length ?? 0));
      return {
        text: `${placed}/${total} anchored · derived`,
        title: 'Pad positions come from the production gerbers — nothing to place by hand.',
        done: placed === total,
      };
    }
    if (builtIn !== undefined && !manual && props.connector !== undefined) {
      const drawn = drawnTerminals(builtIn);
      // the definition itself is the authority on which pins there are
      const pins = props.connector.pins.map((pin) => pin.id);
      const placed = pins.filter((id) => drawn.has(id)).length;
      return {
        text: `${placed}/${pins.length} anchored · derived`,
        title: 'Pin positions come from the built-in drawing; only uploaded artwork needs pins placed by hand.',
        done: placed === pins.length,
      };
    }
    return {
      text: `${progress.anchored.length}/${total} anchored`,
      title: 'Pins placed by hand on the uploaded picture — click a pin, then its spot.',
      done: progress.complete,
    };
  })();

  const save = async (): Promise<void> => {
    if (detail === undefined || frameView === undefined) return;
    setSaving(true);
    setProblem(undefined);
    const result = await adapter.saveAnchors(defId, {
      anchorFrame: frameView.view,
      pinAnchors: state.anchors,
    });
    setSaving(false);
    if (!result.ok) {
      setProblem({
        message: result.message,
        ...(result.hint === undefined ? {} : { hint: result.hint }),
        ...(result.issues === undefined ? {} : { issues: result.issues }),
      });
      return;
    }
    setDetail(result.value);
    setState(beginAnchoring(result.value.pinAnchors));
    setNotice('Anchors saved. The schematic preview is already drawing them.');
    onOverlay(defId, result.value, art);
  };

  if (loadProblem !== undefined) {
    return (
      <div className="cs-artwork-detail">
        <Problem message="The studio could not read this definition's artwork." hint={loadProblem} />
      </div>
    );
  }
  if (detail === undefined) return <p className="cs-empty">loading…</p>;

  return (
    <div className="cs-artwork-detail">
      <header className="cs-artwork-head">
        <strong>{definition?.label ?? defId}</strong>
        <span className="cs-doc-id">{defId}</span>
        {definition === undefined ? (
          <span className="cs-chip is-error">not a definition this catalog knows</span>
        ) : (
          <span className="cs-chip">
            {definition.kind} · {terminals.length} terminal{terminals.length === 1 ? '' : 's'}
          </span>
        )}
        <span className="cs-spacer" />
        {gerber ? (
          <span
            className="cs-chip"
            title="This artwork is rendered from the production gerbers by scripts/import-gerbers.ts — not something to draw or anchor by hand. Regenerate it there if the board revision changed."
          >
            From gerbers — read-only
          </span>
        ) : null}
        <span className={classes('cs-chip', anchorChip.done && 'is-done')} title={anchorChip.title}>
          {anchorChip.text}
        </span>
      </header>

      {gerber && detail.meta !== undefined ? (
        <GerberBoardArt
          meta={detail.meta}
          art={art}
          {...(adapter.saveEntryGuides === undefined
            ? {}
            : {
                onSaveGuides: async (guides: readonly EntryGuide[]): Promise<string | undefined> => {
                  const result = await adapter.saveEntryGuides!(defId, guides);
                  if (!result.ok) return `${result.message} ${result.hint ?? ''}`.trim();
                  setDetail(result.value);
                  onOverlay(defId, result.value, art);
                  return undefined;
                },
              })}
        />
      ) : (
        <>
          {builtIn !== undefined && props.connector !== undefined ? (
            <BuiltInConnectorArt
              def={props.connector}
              art={builtIn}
              {...(props.body === undefined ? {} : { body: props.body })}
              {...(props.sharedBy === undefined ? {} : { sharedBy: props.sharedBy })}
            />
          ) : props.connector !== undefined ? (
            <p className="cs-empty" title="connector-art.ts has no drawing for this family">
              No built-in drawing for {props.connector.family ?? 'this family'} — the builder shows a pin list.
            </p>
          ) : null}
          <details className="cs-artwork-extra" open={builtIn === undefined || manual || detail.views.length > 0}>
            <summary title={`Optional: your own picture, shown alongside the built-in drawing. ${ARTWORK_FORMATS_HELP}.`}>
              Uploaded artwork <span className="cs-chip">{builtIn === undefined ? 'for pin anchors' : 'optional'}</span>
            </summary>
          <section className="cs-artwork-uploads">
            {detail.uploadableViews.map((view) => {
              const existing = detail.views.find((entry) => entry.view === view);
              return (
                <UploadBox
                  key={view}
                  defId={defId}
                  view={view}
                  adapter={adapter}
                  {...(existing === undefined ? {} : { existing })}
                  {...(props.assets === undefined ? {} : { assets: props.assets })}
                  onUploaded={() => void refresh()}
                />
              );
            })}
            <p
              className="cs-artwork-derived-note"
              title="Mirroring a pinout by eye is the classic wiring error, so this is one job the tool does not hand back to you."
            >
              Solder side / board underside: generated by flipping the face — never uploaded.
            </p>
          </section>

          {frameView === undefined || frame === undefined ? (
            <p className="cs-empty">
              Upload a picture above, and the pin list appears here for you to click onto it.
            </p>
          ) : (
            <section className="cs-artwork-anchoring">
          <div className="cs-artwork-checklist">
            <div className="cs-artwork-checklist-head">
              <strong title="Click a pin, then click where it sits on the picture. Drag a dot to nudge it. Scroll to zoom, drag the background to move around.">
                Pins
              </strong>
              <span className="cs-count">
                {progress.todo.length} to place
                {detail?.usedBy === undefined ? null : (
                  <span title="unplaced pins a cable solders to"> · {progress.todo.filter((id) => (detail.usedBy?.[id]?.length ?? 0) > 0).length} used</span>
                )}
              </span>
            </div>
            <ul className="cs-scroll cs-artwork-terminals">
              {terminals.map((terminal) => {
                const done = isAnchored(terminal, state.anchors);
                const usedBy = detail?.usedBy?.[terminal.id] ?? [];
                return (
                  <li key={terminal.id}>
                    <button
                      type="button"
                      {...(detail?.usedBy === undefined
                        ? {}
                        : { title: usedBy.length === 0 ? 'no cable solders here' : `soldered in ${usedBy.length === 1 ? usedBy[0] : `${usedBy.length} cables`}` })}
                      data-used={detail?.usedBy === undefined ? undefined : usedBy.length > 0}
                      className={classes(
                        'cs-artwork-terminal',
                        done && 'is-done',
                        state.armed === terminal.id && 'is-armed',
                      )}
                      aria-pressed={state.armed === terminal.id}
                      onClick={() => setState((current) => armTerminal(current, terminal.id))}
                    >
                      <span className="cs-artwork-tick">{done ? '✓' : '·'}</span>
                      <span className="cs-artwork-tid">{terminal.id}</span>
                      {terminal.label === undefined ? null : (
                        <span className="cs-artwork-tlabel">{terminal.label}</span>
                      )}
                    </button>
                    {done ? (
                      <button
                        type="button"
                        className="cs-artwork-clear"
                        title={`take ${terminal.id} off the picture`}
                        onClick={() => setState((current) => clearAnchor(current, terminal.id))}
                      >
                        ×
                      </button>
                    ) : null}
                  </li>
                );
              })}
            </ul>
            <div className="cs-artwork-actions">
              <button
                type="button"
                disabled={terminals.length === 0}
                onClick={() =>
                  setState((current) => {
                    const next = nextUnanchored(terminals, current.anchors);
                    return next === undefined ? current : armTerminal(current, next);
                  })
                }
              >
                arm the next one
              </button>
              <button type="button" disabled={!dirty || saving} onClick={() => void save()}>
                {saving ? 'saving…' : 'save anchors'}
              </button>
            </div>
            {missingSentence === undefined ? null : <p className="cs-doc-warning">{missingSentence}</p>}
            {progress.stray.length === 0 ? null : (
              <p className="cs-doc-warning">
                {progress.stray.join(', ')} {progress.stray.length === 1 ? 'is' : 'are'} anchored but
                no longer {progress.stray.length === 1 ? 'a terminal' : 'terminals'} of this part —
                saving will be refused until {progress.stray.length === 1 ? 'it is' : 'they are'}{' '}
                removed.
              </p>
            )}
            {problem === undefined ? null : (
              <Problem {...problem} onDismiss={() => setProblem(undefined)} />
            )}
            {notice === undefined ? null : (
              <p className="cs-artwork-notice" role="status">
                {notice}
              </p>
            )}
          </div>

          <div className="cs-artwork-stages">
            <AnchorStage
              frame={frame}
              art={art[frameView.view]}
              anchors={state.anchors}
              {...(state.armed === undefined ? {} : { armed: state.armed })}
              {...(state.dragging === undefined ? {} : { dragging: state.dragging })}
              live
              label={`${viewLabel(frameView.view)} — the one you anchor`}
              onPlace={(point) => {
                setNotice(undefined);
                setState((current) => placeArmed(current, point, terminals));
              }}
              onGrab={(id) => setState((current) => startDrag(current, id))}
              onDragTo={(point) =>
                setState((current) =>
                  current.dragging === undefined
                    ? current
                    : moveAnchor(current, current.dragging, point),
                )
              }
              onRelease={() => setState((current) => endDrag(current))}
            />
            <div className="cs-artwork-mirror">
              <AnchorStage
                frame={frame}
                art={art[frameView.view]}
                anchors={mirrored}
                live={false}
                flip={mirrorAxis}
                label={`${mirrorName === undefined ? 'The other side' : viewLabel(mirrorName)} — generated`}
              />
              <p
                className="cs-artwork-blurb"
                title={`Worked out from the anchors on the left by flipping them across the ${mirrorAxis === 'x' ? 'vertical' : 'horizontal'} centre line — you never enter it, and it updates as you place each pin.`}
              >
                Generated from the anchors on the left.
              </p>
            </div>
          </div>
            </section>
          )}
          </details>
        </>
      )}

      {detail.issues.length === 0 ? null : (
        <ul className="cs-scroll cs-artwork-issues">
          {detail.issues.map((issue, index) => (
            <li key={`${issue.code}-${index}`} className={classes('cs-issue', issue.severity === 'error' && 'is-error')}>
              <span className="cs-issue-code">{issue.code}</span>
              {issue.message}
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}

