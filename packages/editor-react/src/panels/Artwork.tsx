/**
 * `board-top`/`board-bottom` pads, flattened to one dot per physical pad —
 * a terminal with more than one pad on a side (a GND spread across several)
 * gets a suffixed key so none collide.
 */
function padAnchorsOnSide(
  meta: DepictionMeta,
  side: 'top' | 'bottom',
  frame: Frame,
): Record<string, PinAnchor> {
  const out: Record<string, PinAnchor> = {};
  const pads = padsOnSide(meta, side, { width: frame.widthUnits, height: frame.heightUnits });
  for (const [terminal, list] of pads) {
    list.forEach(({ pad }: { pad: BoardPad; primary: boolean }, index: number) => {
      const key = list.length === 1 ? terminal : `${terminal}·${index}`;
      out[key] = { x: pad.x, y: pad.y };
    });
  }
  return out;
}

/** Where the default guide's `src` says it came from (a person then adjusts it). */
const DEFAULT_GUIDE_SRC =
  "Default (inferred): square to the row's pad approach axis, 1.5 mm outside the Edge.Cuts outline, 1.5 mm past the end pads — set in the Library guide editor.";

type GuideHandle = 'from' | 'to' | 'offset';

/**
 * One face's entry guides over its gerber art: the
 * guide, each pad's slot and straight lead, and three handles — the middle
 * one moves the guide square to itself (its offset from the edge; it stays
 * parallel to the row, square to the pads' approach axis), the end ones
 * slide its ends along it.
 */
function GuideOverlay(props: {
  meta: DepictionMeta;
  side: 'top' | 'bottom';
  guides: readonly EntryGuide[];
  width: number;
  pxPerUnit: number;
  editable: boolean;
  onChange: (index: number, guide: EntryGuide) => void;
}): JSX.Element {
  const { meta, side, guides, width, pxPerUnit, editable, onChange } = props;
  const drag = useRef<{ index: number; handle: GuideHandle } | undefined>(undefined);
  // anchor frame → this face's own picture (the bottom is mirrored about x)
  const px = (x: number, y: number): XY => ({ x: (side === 'top' ? x : width - x) * pxPerUnit, y: y * pxPerUnit });
  const toUnits = (event: ReactPointerEvent<SVGElement>): XY => {
    const svg = event.currentTarget.ownerSVGElement;
    const rect = svg?.getBoundingClientRect();
    const ux = (event.clientX - (rect?.left ?? 0)) / pxPerUnit;
    const uy = (event.clientY - (rect?.top ?? 0)) / pxPerUnit;
    return { x: side === 'top' ? ux : width - ux, y: uy };
  };
  return (
    <g className="cs-guides">
      {guides.map((guide, index) => {
        if (guide.side !== side) return null;
        const from = px(guide.from[0], guide.from[1]);
        const to = px(guide.to[0], guide.to[1]);
        const mid = { x: (from.x + to.x) / 2, y: (from.y + to.y) / 2 };
        const handle = (kind: GuideHandle, at: XY, title: string): JSX.Element => (
          <circle
            key={kind}
            className={classes('cs-guide-handle', kind === 'offset' && 'is-offset')}
            data-guide-handle={`${side}:${index}:${kind}`}
            cx={at.x}
            cy={at.y}
            r={kind === 'offset' ? 5.5 : 4.5}
            onPointerDown={(event) => {
              event.stopPropagation();
              drag.current = { index, handle: kind };
              event.currentTarget.setPointerCapture?.(event.pointerId);
            }}
            onPointerMove={(event) => {
              const active = drag.current;
              if (active === undefined || active.index !== index || active.handle !== kind) return;
              const point = toUnits(event);
              onChange(index, kind === 'offset' ? offsetGuideTo(guide, point) : extendGuideTo(guide, kind, point));
            }}
            onPointerUp={() => {
              drag.current = undefined;
            }}
          >
            <title>{title}</title>
          </circle>
        );
        return (
          <g key={index} className="cs-guide">
            {guideSlots(meta, guide).map((slot) => {
              const pad = px(slot.pad.x, slot.pad.y);
              const at = px(slot.slot.x, slot.slot.y);
              return (
                <g key={slot.ref} className={classes('cs-guide-slot', !slot.clear && 'is-blocked')}>
                  <line x1={pad.x} y1={pad.y} x2={at.x} y2={at.y} />
                  <circle cx={at.x} cy={at.y} r={2.2}>
                    <title>{`${slot.ref}${slot.straight ? '' : ' · aimed through the gap'}${slot.clear ? '' : ' · crosses a pad'}`}</title>
                  </circle>
                </g>
              );
            })}
            <line className="cs-guide-line" x1={from.x} y1={from.y} x2={to.x} y2={to.y}>
              <title>{`Entry guide · ${guide.pads.join(' ')} — ${guide.src}`}</title>
            </line>
            {editable ? (
              <>
                {handle('from', from, 'Drag to move this end along the guide')}
                {handle('to', to, 'Drag to move this end along the guide')}
                {handle('offset', mid, "Drag to set the guide's distance from the board edge — it stays parallel to the row")}
              </>
            ) : null}
          </g>
        );
      })}
    </g>
  );
}

function sameGuides(a: readonly EntryGuide[], b: readonly EntryGuide[]): boolean {
  return JSON.stringify(a) === JSON.stringify(b);
}

/**
 * A gerber-sourced board's artwork: the production fabrication output
 * (`scripts/import-gerbers.ts`), not something anyone draws or anchors by
 * hand — the same reason the tool owns the solder-side mirror is why it owns
 * this. Reuses `board-art.ts`'s own pad-reflection helper (`padsOnSide`)
 * rather than re-deriving which pad lands on which face.
 *
 * The one hand-set thing on it: each angled pad row's **entry guide**
 *, drawn over the art and dragged into place; a face
 * with an angled row but no stored guide starts from the default.
 */
function GerberBoardArt(props: {
  meta: DepictionMeta;
  art: Record<string, DepictionArtwork>;
  onSaveGuides?: (guides: readonly EntryGuide[]) => Promise<string | undefined>;
}): JSX.Element {
  const { meta, art, onSaveGuides } = props;
  const top = meta.views['board-top'];
  const bottom = meta.views['board-bottom'];
  const topFrame = frameOf(top);
  const stored = useMemo(() => meta.entryGuides ?? [], [meta]);
  const topArt = art['board-top'];
  const defaults = useMemo(() => {
    const source = topArt?.kind === 'vector' ? topArt.source : undefined;
    return defaultEntryGuides(meta, source === undefined ? undefined : boardOutlineFromSvg(source), DEFAULT_GUIDE_SRC);
  }, [meta, topArt]);
  // stored guides win; a face with an angled row and none stored starts from its default
  const initial = useMemo(
    () => [...stored, ...defaults.filter((guide) => !stored.some((own) => own.side === guide.side))],
    [stored, defaults],
  );
  const [guides, setGuides] = useState<EntryGuide[]>(initial);
  const [saving, setSaving] = useState(false);
  const [problem, setProblem] = useState<string | undefined>(undefined);
  useEffect(() => setGuides(initial), [initial]);
  const dirty = !sameGuides(guides, stored);
  const change = useCallback((index: number, guide: EntryGuide): void => {
    setGuides((current) => current.map((own, at) => (at === index ? guide : own)));
  }, []);

  if (topFrame === undefined) {
    return <p className="cs-empty">This board's gerber artwork has no usable frame.</p>;
  }
  const bottomFrame = frameOf(bottom) ?? topFrame;
  const topAnchors = padAnchorsOnSide(meta, 'top', topFrame);
  const bottomAnchors = padAnchorsOnSide(meta, 'bottom', topFrame);
  // the build's mounted parts over each face — the same overlay the canvas
  // board node draws (y1u.17/18), unturned and at the canvas's own scale
  const hasParts = (side: 'top' | 'bottom'): boolean =>
    (meta.components?.parts ?? []).some((part) => part.side === side);
  const editable = onSaveGuides !== undefined;
  const hasGuides = guides.length > 0;
  const overlayFor =
    (side: 'top' | 'bottom') =>
    (pxPerUnit: number): ReactNode => (
      <>
        {hasParts(side) ? (
          <BoardParts
            parts={partsOnSide(meta, side, { width: topFrame.widthUnits, height: topFrame.heightUnits }, 0, pxPerUnit)}
            labels
          />
        ) : null}
        {hasGuides ? (
          <GuideOverlay
            meta={meta}
            side={side}
            guides={guides}
            width={topFrame.widthUnits}
            pxPerUnit={pxPerUnit}
            editable={editable}
            onChange={change}
          />
        ) : null}
      </>
    );
  const save = async (): Promise<void> => {
    if (onSaveGuides === undefined) return;
    setSaving(true);
    setProblem(await onSaveGuides(guides));
    setSaving(false);
  };
  const overlays = (side: 'top' | 'bottom'): { overlay?: (pxPerUnit: number) => ReactNode } =>
    hasParts(side) || hasGuides ? { overlay: overlayFor(side) } : {};

  return (
    <section className="cs-artwork-gerber">
      {hasGuides ? (
        <div className="cs-guide-bar">
          <span
            className={classes('cs-chip', !dirty && stored.length > 0 && 'is-done')}
            title="Entry guides: where wires to an angled pad row reach the board, before the straight lead in. Drag a guide's middle handle to set its distance from the edge, its end handles to set its length."
          >
            {guides.length} entry guide{guides.length === 1 ? '' : 's'}
            {dirty ? ' · unsaved' : ''}
          </span>
          <span className="cs-spacer" />
          {editable ? (
            <>
              <button
                type="button"
                disabled={sameGuides(guides, defaults)}
                title="Put every guide back to its default: square to the row, 1.5 mm outside the board edge"
                onClick={() => setGuides(defaults)}
              >
                default
              </button>
              <button type="button" disabled={!dirty} title="Undo the changes since the last save" onClick={() => setGuides(initial)}>
                revert
              </button>
              <button
                type="button"
                disabled={!dirty || saving}
                title="Write the guides into this board's reviewed kicad-map (and its manifest)"
                onClick={() => void save()}
              >
                {saving ? 'saving…' : 'save guides'}
              </button>
            </>
          ) : null}
        </div>
      ) : null}
      {problem === undefined ? null : <Problem message={problem} onDismiss={() => setProblem(undefined)} />}
      <div className="cs-artwork-stages">
        <AnchorStage
          frame={topFrame}
          art={art['board-top']}
          anchors={topAnchors}
          live={false}
          label="Board top"
          margin={hasGuides ? 40 : 0}
          {...overlays('top')}
        />
        <AnchorStage
          frame={bottomFrame}
          art={art['board-bottom']}
          anchors={bottomAnchors}
          live={false}
          label="Board bottom"
          margin={hasGuides ? 40 : 0}
          {...overlays('bottom')}
        />
      </div>
    </section>
  );
}

