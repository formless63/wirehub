interface StageProps {
  frame: Frame;
  art: DepictionArtwork | undefined;
  anchors: Record<string, PinAnchor>;
  /** ids drawn as "this is the one you are placing" */
  armed?: string;
  /** live means clicks place and drags move; a mirror preview is not live */
  live: boolean;
  /**
   * Draw the *picture* reversed. The anchors handed in are already reflected;
   * this is what makes the preview look like the other side rather than like
   * the same side with the pins jumbled.
   */
  flip?: 'x' | 'y';
  label: string;
  onPlace?: (point: XY) => void;
  onGrab?: (id: string) => void;
  onDragTo?: (point: XY) => void;
  onRelease?: () => void;
  dragging?: string;
  /**
   * Extra drawing over the picture (a board's mounted parts, 50a.38), built
   * for the picture's current on-screen scale — CSS px per frame unit — so
   * its text stays at screen size while it pans and zooms with the picture.
   */
  overlay?: (pxPerUnit: number) => ReactNode;
  /** clear air (px) kept round the fitted picture — room for a board's entry guides outside its edge */
  margin?: number;
}

/**
 * The picture, at whatever zoom and pan the user has it, with the anchors
 * drawn on top.
 *
 * Pan and zoom are hand-rolled — wheel to zoom about the cursor, drag the
 * background to pan — because the whole interaction is four lines of arithmetic
 * from `artwork.ts` and a library would be a dependency for nothing.
 */
function AnchorStage(props: StageProps): JSX.Element {
  const box = useRef<HTMLDivElement>(null);
  const [view, setView] = useState<ViewTransform>(IDENTITY_VIEW);
  const [stage, setStage] = useState<Stage>({ width: 0, height: 0 });
  const panning = useRef<XY | undefined>(undefined);

  useEffect(() => {
    const element = box.current;
    if (element === null) return;
    const measure = (): void =>
      setStage({ width: element.clientWidth, height: element.clientHeight });
    measure();
    if (typeof ResizeObserver === 'undefined') return;
    const observer = new ResizeObserver(measure);
    observer.observe(element);
    return () => observer.disconnect();
  }, []);

  const margin = props.margin ?? 0;
  const place = useMemo(() => {
    const fitted = placement(
      props.frame,
      { width: Math.max(0, stage.width - margin * 2), height: Math.max(0, stage.height - margin * 2) },
      view,
    );
    return { ...fitted, offsetX: fitted.offsetX + margin, offsetY: fitted.offsetY + margin };
  }, [props.frame, stage, view, margin]);
  const { overlay: buildOverlay } = props;
  const overlay = useMemo(
    () => (buildOverlay === undefined || place.scale <= 0 ? undefined : buildOverlay(place.scale)),
    [buildOverlay, place.scale],
  );

  const stagePoint = (event: ReactPointerEvent | ReactWheelEvent): XY => {
    const rect = box.current?.getBoundingClientRect();
    return {
      x: event.clientX - (rect?.left ?? 0),
      y: event.clientY - (rect?.top ?? 0),
    };
  };

  const onPointerDown = (event: ReactPointerEvent<HTMLDivElement>): void => {
    if (!props.live) return;
    const grabbed = (event.target as HTMLElement).dataset['anchorId'];
    if (grabbed !== undefined) {
      props.onGrab?.(grabbed);
      event.currentTarget.setPointerCapture(event.pointerId);
      return;
    }
    if (props.armed !== undefined) {
      props.onPlace?.(anchorAt(stagePoint(event), props.frame, place));
      return;
    }
    panning.current = stagePoint(event);
    event.currentTarget.setPointerCapture(event.pointerId);
  };

  const onPointerMove = (event: ReactPointerEvent<HTMLDivElement>): void => {
    const at = stagePoint(event);
    if (props.dragging !== undefined) {
      props.onDragTo?.(anchorAt(at, props.frame, place));
      return;
    }
    const from = panning.current;
    if (from === undefined) return;
    panning.current = at;
    setView((current) => panBy(current, at.x - from.x, at.y - from.y));
  };

  const onPointerUp = (): void => {
    panning.current = undefined;
    props.onRelease?.();
  };

  return (
    <div className="cs-artwork-stage-wrap">
      <div className="cs-artwork-stage-bar">
        <span>{props.label}</span>
        <span className="cs-spacer" />
        <button type="button" onClick={() => setView(IDENTITY_VIEW)}>
          fit
        </button>
        <span className="cs-chip">{Math.round(view.zoom * 100)}%</span>
      </div>
      <div
        ref={box}
        className={classes('cs-artwork-stage', props.live && props.armed !== undefined && 'is-placing')}
        onPointerDown={onPointerDown}
        onPointerMove={onPointerMove}
        onPointerUp={onPointerUp}
        onPointerCancel={onPointerUp}
        onWheel={(event) => {
          const factor = Math.exp(-event.deltaY / 400);
          setView((current) => zoomAbout(current, stagePoint(event), factor, props.frame, stage));
        }}
      >
        {artworkSrc(props.art) === undefined ? (
          <p className="cs-empty">no picture to show</p>
        ) : (
          <img
            className="cs-artwork-img"
            src={artworkSrc(props.art)}
            alt=""
            draggable={false}
            style={{
              position: 'absolute',
              left: `${place.offsetX}px`,
              top: `${place.offsetY}px`,
              width: `${props.frame.widthUnits * place.scale}px`,
              height: `${props.frame.heightUnits * place.scale}px`,
              ...(props.flip === undefined
                ? {}
                : { transform: props.flip === 'x' ? 'scaleX(-1)' : 'scaleY(-1)' }),
            }}
          />
        )}
        {overlay === undefined ? null : (
          <svg
            className="cs-artwork-overlay"
            viewBox={`0 0 ${props.frame.widthUnits * place.scale} ${props.frame.heightUnits * place.scale}`}
            style={{
              position: 'absolute',
              left: `${place.offsetX}px`,
              top: `${place.offsetY}px`,
              width: `${props.frame.widthUnits * place.scale}px`,
              height: `${props.frame.heightUnits * place.scale}px`,
            }}
          >
            {overlay}
          </svg>
        )}
        {Object.entries(props.anchors).map(([id, anchor]) => {
          const at = toStage(anchor, place);
          return (
            <span
              key={id}
              className={classes('cs-anchor-dot', props.armed === id && 'is-armed')}
              data-anchor-id={props.live ? id : undefined}
              title={`${id} — ${anchor.x}, ${anchor.y}`}
              style={{ left: `${at.x}px`, top: `${at.y}px` }}
            >
              <b data-anchor-id={props.live ? id : undefined} />
              <i>{id}</i>
            </span>
          );
        })}
      </div>
    </div>
  );
}

